export const DICTS: Record<Locale, Dict> = { "zh-CN": zhCN, en };

/**
 * Substitute `{name}` placeholders.
 *   t("dashboard.quota.credits", { used: 5, limit: 100 })
 *   // → "5 / 100 积分"
 */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const v = vars[key];
    return v === undefined ? `{${key}}` : String(v);
  });
}

/**
 * Resolve a translation key in a given locale.
 * Fallback chain: locale → en → raw key (visible during dev).
 */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[locale] ?? DICTS.en;
  const raw =
    dict[key] ??
    DICTS.en[key] ??
    key;
  return interpolate(raw, vars);
}

/**
 * Parse a locale string from a cookie value or Accept-Language header.
 * Accepts "zh-CN", "zh", "en", "en-US", etc.
 * Defaults to DEFAULT_LOCALE if unrecognized.
 */
export function parseLocale(input: string | undefined | null): Locale {
  if (!input) return DEFAULT_LOCALE;
  const tag = input.trim().toLowerCase().split(",")[0]?.split(";")[0]?.trim() ?? "";
  if (tag.startsWith("zh")) return "zh-CN";
  if (tag.startsWith("en")) return "en";
  return DEFAULT_LOCALE;
}
