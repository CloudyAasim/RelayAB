/**
 * src/lib/announcements/links.ts
 *
 * One place that knows where a single notice is read in full.
 *
 * Two reader surfaces link there — the strip at the top of every page, and the
 * "read the full notice" affordance on each card in the centre — and a
 * hand-written template string in each is how one of them ends up pointing at a
 * route that was renamed. It lives beside the client-safe types rather than in
 * the repository because the strip is a client component, and importing the
 * repository for a URL would drag `node:sqlite` into the browser bundle.
 */

/**
 * The reader's page for one announcement.
 *
 * The id is encoded: it is generated by `generateId` today and therefore safe,
 * but this is also the place a future "custom slug" would land, and a slug with
 * a space or a `#` in it would break the link rather than the page.
 */
export function announcementHref(id: string): string {
  return `/dashboard/announcements/${encodeURIComponent(id)}`;
}

/** The centre, for the "all of them" links. */
export const ANNOUNCEMENTS_HREF = "/dashboard/announcements";