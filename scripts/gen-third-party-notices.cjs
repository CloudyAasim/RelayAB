/**
 * scripts/gen-third-party-notices.cjs
 *
 * Generate `THIRD-PARTY-NOTICES.md` from what is actually installed.
 *
 * Why this exists: the licence page lists the *direct* dependencies, but the
 * Docker image ships the whole production dependency tree — including packages
 * with obligations the direct list never mentions. At the time this was written
 * that tree contained 190 MIT packages, 13 Apache-2.0, 8 ISC, one BSD-3-Clause,
 * one CC-BY-4.0 (caniuse-lite) and one `Apache-2.0 AND LGPL-3.0-or-later`
 * (`@img/sharp-libvips-linux-*`, pulled in by Next's optional `sharp`). LGPL and
 * CC-BY both require a notice, and Apache-2.0 requires a copy of its licence.
 *
 * Output policy, chosen so the file stays reviewable:
 *   - every installed package is listed by `name@version` under its licence;
 *   - for licences that are not MIT/ISC, the full licence text is included
 *     (Apache-2.0, BSD-3-Clause, CC-BY-4.0, LGPL-3.0, 0BSD, unknown);
 *   - MIT/ISC texts are not copied here — every package ships its own LICENCE
 *     file in `node_modules`, and the image keeps it.
 *
 * Run: node scripts/gen-third-party-notices.cjs
 */
const { readFileSync, readdirSync, writeFileSync, existsSync, statSync } = require("node:fs");
const { join, dirname } = require("node:path");

const ROOT = join(__dirname, "..");
const PNPM = join(ROOT, "node_modules", ".pnpm");

/** Read a package's own licence file, if it has one. */
function readLicenseText(dir) {
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return null;
  }
  const file = names
    .filter((name) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(name))
    .sort((a, b) => (/notice/i.test(a) ? 1 : 0) - (/notice/i.test(b) ? 1 : 0))[0];
  if (!file) return null;
  try {
    const text = readFileSync(join(dir, file), "utf8").trim();
    // A few packages ship a stub that only says "see the repository".
    return text.length > 20 ? text : null;
  } catch {
    return null;
  }
}

function spdxOf(pkg) {
  const raw = pkg.license ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(" OR ") : "");
  if (typeof raw === "string" && raw.trim()) return raw.trim();
  return "UNKNOWN";
}

function repoOf(pkg) {
  const repo = pkg.repository;
  const url = typeof repo === "string" ? repo : repo?.url;
  if (!url) return "";
  return String(url)
    .replace(/^git\+/, "")
    .replace(/\.git$/, "")
    .replace(/^ssh:\/\/git@/, "https://")
    .replace(/^git@([^:]+):/, "https://$1/");
}

/**
 * Every package under pnpm's store, deduplicated by name@version.
 *
 * The store keeps each package at `<entry>/node_modules/<name>`, and scoped
 * packages are two directories deep (`@img/sharp-libvips-linux-x64`), so the
 * directory is walked rather than reconstructed from the entry name — the first
 * version of this script guessed the name and silently dropped every scoped
 * package, which is exactly where the LGPL one lives.
 */
function collect() {
  const found = new Map();

  const add = (dir) => {
    const manifestPath = join(dir, "package.json");
    if (!existsSync(manifestPath)) return;
    let pkg;
    try {
      pkg = JSON.parse(readFileSync(manifestPath, "utf8"));
    } catch {
      return;
    }
    if (!pkg.name || !pkg.version) return;
    const key = `${pkg.name}@${pkg.version}`;
    if (found.has(key)) return;
    found.set(key, {
      name: pkg.name,
      version: pkg.version,
      license: spdxOf(pkg),
      repo: repoOf(pkg),
      text: readLicenseText(dir),
      private: pkg.private === true,
    });
  };

  let dirs;
  try {
    dirs = readdirSync(PNPM);
  } catch {
    return found;
  }
  for (const entry of dirs) {
    const base = join(PNPM, entry, "node_modules");
    if (!existsSync(base)) continue;
    for (const child of readdirSync(base)) {
      if (child.startsWith("@")) {
        const scope = join(base, child);
        for (const sub of readdirSync(scope)) add(join(scope, sub));
      } else {
        add(join(base, child));
      }
    }
  }
  return found;
}

const packages = [...collect().values()]
  .filter((pkg) => !pkg.private)
  .sort((a, b) => a.name.localeCompare(b.name));

const byLicense = new Map();
for (const pkg of packages) {
  const list = byLicense.get(pkg.license) ?? [];
  list.push(pkg);
  byLicense.set(pkg.license, list);
}

/** Licences whose text must travel with the distribution. */
const NEEDS_TEXT = (license) =>
  !/^(MIT|ISC|0BSD|Unlicense|CC0-1\.0)$/.test(license) || license === "UNKNOWN";

const lines = [
  "# Third-party notices",
  "",
  "Generated by `node scripts/gen-third-party-notices.cjs` from the installed",
  "dependency tree. **Do not edit by hand** — regenerate after changing",
  "dependencies.",
  "",
  "This repository copy comes from the development tree, which is a superset of",
  "what the image ships: the Docker build regenerates this file inside its",
  "production-dependencies stage, so the copy inside an image describes that image.",
  "Every package also ships its own licence file under `node_modules/<package>/`.",
  "",
  `Packages: **${packages.length}** (${[...byLicense.entries()]
    .map(([license, list]) => `${list.length} ${license}`)
    .join(", ")})`,
  "",
];

for (const [license, list] of [...byLicense.entries()].sort((a, b) => b[1].length - a[1].length)) {
  lines.push(`## ${license} (${list.length})`, "");
  for (const pkg of list) {
    lines.push(`- \`${pkg.name}@${pkg.version}\`${pkg.repo ? ` — ${pkg.repo}` : ""}`);
  }
  lines.push("");

  if (NEEDS_TEXT(license)) {
    lines.push(`### ${license} licence text`, "");
    const withText = list.filter((pkg) => pkg.text);
    if (withText.length === 0) {
      lines.push(
        "No package in this group ships a licence file; refer to the project URL above.",
        "",
      );
    }
    for (const pkg of withText) {
      lines.push(`#### ${pkg.name}@${pkg.version}`, "", "```text", pkg.text, "```", "");
    }
  }
}

writeFileSync(join(ROOT, "THIRD-PARTY-NOTICES.md"), `${lines.join("\n").trimEnd()}\n`, "utf8");
console.log(
  `THIRD-PARTY-NOTICES.md: ${packages.length} packages, ${byLicense.size} licence groups`,
);
